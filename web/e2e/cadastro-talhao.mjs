// Roteiro de navegador do cadastro do talhão (Fase 5, parte). Mesmos pré-requisitos de
// console-plataforma.mjs; usa admin@valtexa.dev.
import { chromium } from 'playwright'
const BASE = 'http://localhost:8765'
const SHOTS = process.argv[2]
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1360, height: 900 } })
p.on('pageerror', (e) => console.log('ERRO JS:', e.message))
const passo = (t) => console.log('✓', t)
await p.goto(`${BASE}/entrar`)
await p.fill('input[type=email]', 'admin@valtexa.dev')
await p.fill('input[type=password]', 'valtexa-demo-2026')
await p.click('button[type=submit]')
await p.getByRole('navigation', { name: 'Navegação principal' }).first().waitFor()
await p.goto(`${BASE}/talhoes`)
await p.getByLabel('Fazendas').waitFor()
passo('lista de fazendas aparece em Talhões')
await p.locator('a[href^="/talhoes/"]').first().click()
await p.getByText('Cadastro do talhão').waitFor()
await p.getByText('Escolher as fileiras de validação').waitFor()
passo('pendências com a próxima ação aparecem')
await p.getByText('Cadastro do talhão').scrollIntoViewIfNeeded()
await p.screenshot({ path: `${SHOTS}/6-talhao-antes.png` })
await p.getByRole('button', { name: 'Editar' }).click()
await p.getByLabel('Espaçamento entre plantas (m)').fill('2,5')
await p.getByLabel('Número de linhas').fill('40')
await p.getByLabel('Fileiras de validação').fill('41')
await p.getByText('O talhão tem 40 linhas').waitFor()
passo('fileira além do número de linhas é recusada na tela')
await p.getByLabel('Fileiras de validação').fill('3-5, 20')
await p.getByLabel('Observações').fill('Curva de nível no canto sul.')
await p.getByRole('button', { name: 'Salvar' }).click()
await p.getByText('3-5, 20').waitFor()
await p.getByText('Curva de nível no canto sul.').waitFor()
passo('salvou e mostra fileiras e observações')
await p.getByText('Cadastro do talhão').scrollIntoViewIfNeeded()
await p.screenshot({ path: `${SHOTS}/7-talhao-depois.png` })
await b.close()
